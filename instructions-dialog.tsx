'use client'

import { Modal } from '@/components/crm/modal'
import {
  Wallet,
  BarChart3,
  Brain,
  Calculator,
  NotebookPen,
  Search,
  Globe,
} from 'lucide-react'
import { BASE_REQUEST_PRICE, COMMISSION_RATE } from '@/lib/calc'
import { fmtNum } from '@/lib/format'

function Section({
  icon,
  title,
  children,
}: {
  icon: React.ReactNode
  title: string
  children: React.ReactNode
}) {
  return (
    <section className="rounded-xl border border-border bg-background/40 p-4">
      <h3 className="flex items-center gap-2 text-sm font-semibold text-foreground">
        <span className="text-[color:var(--primary)]">{icon}</span>
        {title}
      </h3>
      <div className="mt-2 space-y-2 text-sm leading-relaxed text-foreground/85">
        {children}
      </div>
    </section>
  )
}

function Formula({ children }: { children: React.ReactNode }) {
  return (
    <p className="rounded-md border border-dashed border-border bg-card px-3 py-2 font-mono text-[13px] text-foreground/90">
      {children}
    </p>
  )
}

export function InstructionsDialog({
  open,
  onClose,
}: {
  open: boolean
  onClose: () => void
}) {
  return (
    <Modal
      open={open}
      onClose={onClose}
      size="xl"
      title="Инструкция по работе с CRM"
      description="Подробное описание каждой вкладки и логики всех расчётов системы."
    >
      <div className="thin-scroll max-h-[70vh] space-y-4 overflow-y-auto pr-1">
        <Section icon={<Wallet className="size-4" />} title="Вкладка «Баланс»">
          <p>
            Основная вкладка ежедневного учёта. Нажмите кнопку{' '}
            <b>«Заполнить данные»</b>, чтобы открыть форму ввода за день, либо{' '}
            <b>кликните по строке нужного дня</b> в таблице — откроется то же окно
            для редактирования ранее введённых данных.
          </p>
          <p>
            Вы вводите вручную только исходные значения: количество базовых
            заявок, иные поступления, возвраты (шт. и сумма), расходы по 5
            рекламным компаниям, зарплату и прочие расходы. Все производные
            показатели система считает автоматически:
          </p>
          <Formula>
            Сумма поступлений = Кол-во заявок × {fmtNum(BASE_REQUEST_PRICE)} ₽
          </Formula>
          <Formula>
            Итог прихода = Сумма поступлений + Иные пост. (сумма возвратов в
            приходе НЕ учитывается)
          </Formula>
          <Formula>
            Комиссия кассы = {Math.round(COMMISSION_RATE * 100)}% × Сумма
            поступлений (иные поступления комиссией не облагаются)
          </Formula>
          <Formula>
            Итог расхода = Возврат + Комиссия + Реклама + Зарплата + Прочие
            расходы
          </Formula>
          <Formula>Чистая прибыль = Итог прихода − Итог расхода</Formula>
          <Formula>
            Рентабельность, % = Чистая прибыль ÷ Итог прихода × 100
          </Formula>
          <p>
            Колонки сгруппированы по цветам: <b>«Приход»</b> (кол-во заявок, сумма
            поступлений, иные поступления, итог прихода) и <b>«Расход»</b>
            (возвраты, комиссия, реклама, зарплата, прочие, итог расхода). Строки
            автоматически сворачиваются в итоги за неделю и за месяц. Любой день
            можно отредактировать или удалить (значок корзины) и заполнить заново.
          </p>
          <p className="rounded-md border border-[color:var(--primary)]/30 bg-[color:var(--primary)]/10 px-3 py-2 text-[13px]">
            <b>Важно про возвраты.</b> Сумма возврата за день <b>не вычитается</b>{' '}
            из прихода — итог прихода считается как «Сумма поступлений + Иные
            пост.». Вместо этого сумма возврата <b>приплюсовывается к итогу
            расхода</b> вместе с комиссией, рекламой, зарплатой и прочими
            расходами. На итоговую чистую прибыль это влияет так же (возврат её
            уменьшает), но теперь он корректно отражён именно как расход.
          </p>
        </Section>

        <Section icon={<BarChart3 className="size-4" />} title="Вкладка «Статистика»">
          <p>
            Показывает общие данные за выбранный период: <b>Общий доход</b>,{' '}
            <b>Комиссия кассы</b>, <b>Расходы на рекламу</b>, <b>Зарплата</b>,{' '}
            <b>Прочие расходы</b> и <b>Чистая прибыль</b>. По умолчанию выводятся
            данные за последний день; фильтром можно выбрать день, неделю, месяц
            или произвольный период.
          </p>
          <p>
            Графики строятся из тех же дневных значений: динамика прихода/расхода/
            прибыли, сравнение прихода и расхода по дням, структура расходов и
            расходы по рекламным компаниям, а также накопленная прибыль с
            индикатором улучшения или ухудшения относительно предыдущего
            сопоставимого периода.
          </p>
        </Section>

        <Section icon={<Brain className="size-4" />} title="Вкладка «Аналитика»">
          <p>
            Углублённый разбор по всем показателям вкладки «Баланс». Считает
            средние значения, средний чек, ДРР (долю рекламных расходов в приходе),
            долю рекламы в расходах, число прибыльных и убыточных дней, лучший и
            худший день.
          </p>
          <Formula>Средний чек = Итог прихода ÷ Кол-во заявок</Formula>
          <Formula>ДРР, % = Расходы на рекламу ÷ Итог прихода × 100</Formula>
          <p>
            Блок <b>выводов ИИ-аналитика</b> автоматически формирует текстовые
            рекомендации и общий вывод и пересчитывается мгновенно при любом
            изменении данных во вкладке «Баланс».
          </p>
        </Section>

        <Section icon={<Calculator className="size-4" />} title="Вкладка «Калькулятор»">
          <p>
            Полноценный калькулятор со скобками и приоритетом операций (можно
            вводить и с клавиатуры). Слева — сноски с готовыми формулами для
            быстрых ручных расчётов (процент, комиссия, рентабельность, ДРР).
            Справа — блокнот расчётов с возможностью сохранять, редактировать и
            удалять записи. Нажатие «=» сохраняет вычисление в историю.
          </p>
        </Section>

        <Section icon={<NotebookPen className="size-4" />} title="Вкладка «Блокнот»">
          <p>
            Свободные заметки по работе сервиса: договорённости, идеи, задачи.
            Каждую заметку можно создать, отредактировать и удалить.
          </p>
        </Section>

        <Section
          icon={<Search className="size-4" />}
          title="Вкладка «Поисковые инструменты»"
        >
          <p>
            Список полезных ссылок и инструментов с комментариями. Удобно хранить
            рабочие сервисы и доступы в одном месте.
          </p>
        </Section>

        <Section icon={<Globe className="size-4" />} title="Вкладка «Рекламные сайты»">
          <p>
            Связки «Сайт А» (рекламный) ⇄ «Сайт Б» (платёжный) с привязкой к
            рекламной компании и <b>выбором кассы (Platega / Cashera)</b>. Касса
            сохраняется и отображается в списке. Записи можно редактировать и
            удалять.
          </p>
        </Section>

        <p className="rounded-xl border border-[color:var(--positive)]/30 bg-[color:var(--positive)]/10 px-4 py-3 text-xs text-foreground/85">
          Все данные надёжно сохраняются в облачной базе и доступны с любого
          устройства и браузера. Расчёты выполняются с денежным округлением до
          копеек, поэтому суммы никогда не «плывут».
        </p>
      </div>
    </Modal>
  )
}
