'use server'

import { generateText } from 'ai'
import { hasValidSession } from '@/lib/auth/server'

/**
 * Профессиональный ИИ-помощник вкладки «БЛОКНОТ».
 * Все функции работают с выделенным фрагментом текста (или со всем документом),
 * возвращают ТОЛЬКО готовый текст без вступлений и пояснений. Результат сначала
 * показывается пользователю на подтверждение и применяется лишь после согласия.
 */

// Используем самую современную и сильную доступную модель для максимально
// грамотного и профессионального редактирования текста.
const MODEL = 'openai/gpt-5.1'

export type AiMode =
  | 'spelling' // проверка и исправление орфографии и пунктуации
  | 'paragraphs' // логичное разбиение и выравнивание по абзацам
  | 'improve' // улучшить текст (ясность, стиль, читабельность)
  | 'expand' // увеличить объём текста
  | 'shorten' // сократить объём текста
  | 'main_idea' // выписать главную мысль
  | 'professional' // профессионально улучшить по заданным параметрам

const PROMPTS: Record<AiMode, string> = {
  spelling:
    'Ты — профессиональный корректор русского языка. Исправь в тексте все орфографические и пунктуационные ошибки, опечатки и согласование слов. СТРОГО сохрани исходный смысл, стиль, абзацы и порядок изложения. Не добавляй и не удаляй содержание. Верни только исправленный текст.',
  paragraphs:
    'Ты — профессиональный редактор. Разбей текст на логичные, аккуратно выровненные абзацы, улучшая структуру и читабельность. Не меняй смысл и фактическое содержание, не переписывай стиль без необходимости. Верни только переструктурированный текст.',
  improve:
    'Ты — профессиональный редактор и литературный корректор. Улучши текст: повысь ясность, связность, читабельность и стилистику, исправь ошибки. Сохрани исходный смысл и язык оригинала. Верни только улучшенный текст.',
  expand:
    'Ты — профессиональный автор. Увеличь объём текста: раскрой мысли подробнее, добавь уместные детали, примеры и пояснения, сохраняя исходный смысл, тему и стиль. Не выдумывай недостоверных фактов. Верни только расширенный текст.',
  shorten:
    'Ты — профессиональный редактор. Сократи объём текста, сохранив все ключевые мысли и смысл. Убери воду и повторы, сделай формулировки лаконичными. Верни только сокращённый текст.',
  main_idea:
    'Ты — аналитик текста. Кратко и чётко сформулируй главную мысль (основную идею) текста на русском языке в виде нескольких ёмких предложений. Верни только формулировку главной мысли.',
  professional:
    'Ты — профессиональный редактор. Профессионально улучши текст в соответствии с заданными пользователем параметрами. Сохрани исходный смысл и язык оригинала, если параметры не требуют иного. Верни только готовый текст.',
}

export interface TransformInput {
  mode: AiMode
  text: string
  /** Дополнительные параметры/пожелания пользователя (для режима professional). */
  instruction?: string
}

export type TransformResult =
  | { ok: true; text: string }
  | { ok: false; error: string }

export async function transformText(
  input: TransformInput,
): Promise<TransformResult> {
  // Доступ к платному ИИ только для авторизованной сессии.
  if (!(await hasValidSession())) {
    return { ok: false, error: 'Требуется вход в систему.' }
  }
  const text = (input.text ?? '').trim()
  if (!text) {
    return { ok: false, error: 'Выделите или введите текст для обработки.' }
  }
  if (text.length > 20000) {
    return {
      ok: false,
      error: 'Слишком большой фрагмент. Выделите часть текста (до 20 000 символов).',
    }
  }

  const system = PROMPTS[input.mode] ?? PROMPTS.improve
  const extra =
    input.instruction && input.instruction.trim()
      ? `\n\nПараметры и пожелания пользователя: ${input.instruction.trim()}`
      : ''

  try {
    const { text: out } = await generateText({
      model: MODEL,
      system:
        system +
        '\n\nВажно: отвечай на том же языке, что и исходный текст. Не добавляй кавычки, заголовки, пояснения или markdown-разметку — только сам результат.',
      prompt: `Исходный текст:\n\n${text}${extra}`,
    })
    const result = (out ?? '').trim()
    if (!result) {
      return { ok: false, error: 'ИИ вернул пустой ответ. Попробуйте ещё раз.' }
    }
    return { ok: true, text: result }
  } catch (err) {
    console.log('[v0] transformText failed:', err)
    return {
      ok: false,
      error:
        'Не удалось связаться с ИИ-помощником. Проверьте подключение и попробуйте снова.',
    }
  }
}
